'use strict';

const { contextBridge, ipcRenderer } = require('electron');

const send = (channel) => (payload) => ipcRenderer.send(channel, payload);
const invoke = (channel) => (payload) => ipcRenderer.invoke(channel, payload);
const on = (channel) => (cb) => ipcRenderer.on(channel, (_e, data) => cb(data));

contextBridge.exposeInMainWorld('companion', {
  getState: invoke('state:get'),
  getWeather: invoke('weather:get'),
  updateWeatherLocation: invoke('weather:update-location'),
  clearWeatherLocation: invoke('weather:clear-location'),
  getMetrics: invoke('metrics:get'),
  addTask: invoke('tasks:add'),
  toggleTask: invoke('tasks:toggle'),
  deferTask: invoke('tasks:defer'),
  snoozeTask: invoke('tasks:snooze'),
  removeTask: invoke('tasks:remove'),
  clearDone: invoke('tasks:clear-done'),
  chat: (messages, image) => ipcRenderer.invoke('chat:send', { messages, image }),
  setModel: invoke('chat:set-model'),
  getOllamaModels: invoke('ollama:models'),
  diagnoseOllama: invoke('ollama:diagnostics'),
  getSettings: invoke('settings:get'),
  getHistory: invoke('history:get'),
  appendHistory: invoke('history:append'),
  clearHistory: invoke('history:clear'),
  notify: send('notify'),
  setSettings: invoke('settings:set'),
  topProcesses: invoke('sys:processes'),
  killProcess: invoke('sys:kill'),
  cleanupProcesses: invoke('sys:cleanup'),
  clipboardList: invoke('clipboard:list'),
  clipboardRead: invoke('clipboard:read'),
  clipboardCopy: invoke('clipboard:copy'),
  clipboardCapture: invoke('clipboard:push-history'),
  launchApp: invoke('launch:app'),
  getCachedNewsBriefing: invoke('news:cached'),
  getNewsBriefing: invoke('news:briefing'),
  openNewsArticle: invoke('news:open-article'),
  chooseWorkspace: invoke('workspace:select'),
  clearWorkspace: invoke('workspace:clear'),
  getWorkspaceGitStatus: invoke('workspace:git'),
  listWorkspaceFiles: invoke('workspace:list'),
  readWorkspaceFile: invoke('workspace:read'),
  searchWorkspace: invoke('workspace:search'),
  askCodingAgent: invoke('coding:ask'),
  proposeCodeEdit: invoke('coding:propose-edit'),
  applyCodeEdit: invoke('coding:apply-edit'),
  undoCodeEdit: invoke('coding:undo-edit'),
  runCodingCheck: invoke('coding:run-check'),
  getCodingSessions: invoke('coding:sessions:get'),
  resumeCodingSession: invoke('coding:sessions:resume'),
  startCodingSession: invoke('coding:sessions:start'),
  addCodingSessionNote: invoke('coding:sessions:add-note'),
  finishCodingSession: invoke('coding:sessions:finish'),
  followUpCodingSession: invoke('coding:sessions:follow-up'),
  openCode: invoke('code:open'),
  captureScreen: invoke('screen:capture'),
  searchDesktop: invoke('desktop:search'),
  revealDesktopFile: invoke('desktop:reveal'),
  readFile: invoke('file:read'),
  mediaKey: invoke('media:key'),
  autostartGet: invoke('autostart:get'),
  autostartSet: invoke('autostart:set'),
  activity: send('user:activity'),
  setCollapsed: send('ui:collapsed'),
  setDnd: send('ui:dnd'),
  sleep: send('sleep:enter'),
  wake: send('sleep:wake'),
  hit: (hit) => ipcRenderer.send('ui:hit', hit),
  dragStart: send('drag:start'),
  dragEnd: send('drag:end'),
  menu: send('app:menu'),
  quit: send('app:quit'),
  onCursor: on('cursor'),
  onMetrics: on('metrics'),
  onSide: on('layout:side'),
  onTap: on('companion:tap'),
  onDragState: on('drag:state'),
  onSleep: on('mascot:sleep'),
  onWake: on('mascot:wake'),
  onFocusChat: on('focus:chat'),
  onSettings: on('settings:applied'),
  onClipboard: on('clipboard:changed'),
  onMedia: on('media:state'),
  onTasks: on('tasks:updated'),
  onOpenSettings: on('ui:open-settings'),
  onClickThrough: on('click-through:state'),
  onBriefingRequest: on('briefing:show')
});
